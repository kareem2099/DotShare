import { InMemoryTransport, JSONRPCMessage } from '@modelcontextprotocol/server';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { createAgentServer } from '../server';
import { AccountStore } from '../accounts';
import { AgentPublisher } from '../publisher';
import { AGENT_TOOL_NAMES } from '../tool-names';

jest.mock('@napi-rs/keyring', () => ({ Entry: jest.fn() }));

it('negotiates MCP, exposes tools and serves a safe discovery/preview/recovery workflow', async () => {
    const home = fs.mkdtempSync(path.join(os.tmpdir(), 'dotshare-mcp-test-'));
    const values = new Map<string, string>();
    const accounts = new AccountStore(home, { get: key => values.get(key), set: (key, value) => { values.set(key, value); }, delete: key => { values.delete(key); } });
    accounts.add({ id: 'work', name: 'Work account', platform: 'x', credentials: { accessToken: 'private-work-token' } });
    const adapter = jest.fn(async (_target, _credentials, _input, report) => { report({ id: '123', url: 'https://x.com/i/status/123' }); });
    const publisher = new AgentPublisher(accounts, adapter, [home]);
    const server = createAgentServer(publisher);
    const [client, transport] = InMemoryTransport.createLinkedPair();
    let sequence = 0;
    const pending = new Map<number, (value: Record<string, unknown>) => void>();
    client.onmessage = (message: JSONRPCMessage) => {
        if ('id' in message && typeof message.id === 'number') pending.get(message.id)?.(message as unknown as Record<string, unknown>);
    };
    const request = async (method: string, params: Record<string, unknown> = {}): Promise<Record<string, unknown>> => {
        const id = ++sequence;
        const response = new Promise<Record<string, unknown>>((resolve, reject) => {
            const timer = setTimeout(() => reject(new Error(`MCP timeout for ${method}`)), 5000);
            pending.set(id, value => { clearTimeout(timer); pending.delete(id); resolve(value); });
        });
        await client.send({ jsonrpc: '2.0', id, method, params });
        return response;
    };
    try {
        await client.start(); await server.connect(transport);
        const initialized = await request('initialize', { protocolVersion: '2025-11-25', capabilities: {}, clientInfo: { name: 'dotshare-test', version: '1' } });
        expect(initialized.error).toBeUndefined();
        await client.send({ jsonrpc: '2.0', method: 'notifications/initialized' });
        const listing = await request('tools/list');
        const tools = (listing.result as { tools: { name: string; annotations: { readOnlyHint: boolean } }[] }).tools;
        expect(tools.map(tool => tool.name).sort()).toEqual([...AGENT_TOOL_NAMES].sort());
        expect(tools.find(tool => tool.name === 'list_accounts')?.annotations.readOnlyHint).toBe(true);
        expect(tools.find(tool => tool.name === 'publish_post')?.annotations.readOnlyHint).toBe(false);
        expect(tools.find(tool => tool.name === 'render_template')?.annotations.readOnlyHint).toBe(true);
        expect(tools.find(tool => tool.name === 'set_draft_variant')?.annotations.readOnlyHint).toBe(false);
        const listed = await request('tools/call', { name: 'list_accounts', arguments: {} });
        expect(JSON.stringify(listed)).toContain('Work account');
        expect(JSON.stringify(listed)).not.toContain('private-work-token');
        const preview = await request('tools/call', { name: 'preview_post', arguments: { accountIds: ['work'], text: 'Hello' } });
        expect((preview.result as { isError?: boolean }).isError).toBe(false);
        expect(adapter).not.toHaveBeenCalled();
        const presets = await request('tools/call', { name: 'list_templates', arguments: {} });
        expect(JSON.stringify(presets)).toContain('builtin-release');
        const template = await request('tools/call', { name: 'save_template', arguments: { id: 'mcp-recipe', name: 'MCP recipe', content: { text: 'Base {{message}}' }, platformVariants: { x: { text: 'X: {{message}}' } } } });
        expect(JSON.stringify(template)).toContain('"revision":1');
        const missing = await request('tools/call', { name: 'render_template', arguments: { templateId: 'mcp-recipe', expectedRevision: 1 } });
        expect((missing.result as { isError: boolean }).isError).toBe(true);
        const fromTemplate = await request('tools/call', { name: 'create_draft_from_template', arguments: { templateId: 'mcp-recipe', expectedRevision: 1, values: { message: 'Supplied announcement' }, accountIds: ['work'] } });
        const templated = (fromTemplate.result as { structuredContent: { data: { draft: { id: string; status: string } } } }).structuredContent.data.draft;
        expect(templated.status).toBe('Draft');
        const accountVersions = await request('tools/call', { name: 'get_draft_variants', arguments: { draftId: templated.id } });
        expect(JSON.stringify(accountVersions)).toContain('X: Supplied announcement');
        await request('tools/call', { name: 'preview_draft', arguments: { draftId: templated.id, expectedRevision: 1 } });
        const variantEdit = await request('tools/call', { name: 'set_draft_variant', arguments: { draftId: templated.id, expectedRevision: 1, accountId: 'work', variant: { text: 'Reviewed work version' } } });
        expect(JSON.stringify(variantEdit)).toContain('"revision":2');
        expect(JSON.stringify(variantEdit)).toContain('"status":"Draft"');
        const blockedVariant = await request('tools/call', { name: 'set_draft_variant', arguments: { draftId: templated.id, expectedRevision: 1, accountId: 'work', variant: null } });
        expect((blockedVariant.result as { isError: boolean }).isError).toBe(true);
        const deleted = await request('tools/call', { name: 'delete_template', arguments: { templateId: 'mcp-recipe', expectedRevision: 1 } });
        expect(JSON.stringify(deleted)).toContain('"draftsChanged":false');
        expect(adapter).not.toHaveBeenCalled();
        const created = await request('tools/call', { name: 'create_draft', arguments: { title: 'Release', content: { accountIds: ['work'], text: 'Saved draft' } } });
        const draft = (created.result as { structuredContent: { data: { draft: { id: string; revision: number; status: string } } } }).structuredContent.data.draft;
        expect(draft.status).toBe('Draft');
        const previewed = await request('tools/call', { name: 'preview_draft', arguments: { draftId: draft.id, expectedRevision: 1 } });
        const saved = (previewed.result as { structuredContent: { data: { draft: { status: string; published: boolean; preview: { id: string } } } } }).structuredContent.data.draft;
        expect(saved.status).toBe('Preview'); expect(saved.published).toBe(false);
        expect(adapter).not.toHaveBeenCalled();
        const published = await request('tools/call', { name: 'publish_draft', arguments: { draftId: draft.id, expectedRevision: 1, previewId: saved.preview.id, requestId: 'saved-mcp-release-1' } });
        expect(JSON.stringify(published)).toContain('"status":"Published"');
        expect(JSON.stringify(published)).toContain('https://x.com/i/status/123');
        expect(adapter).toHaveBeenCalledTimes(1);
        const savedReplay = await request('tools/call', { name: 'publish_draft', arguments: { draftId: draft.id, expectedRevision: 1, previewId: saved.preview.id, requestId: 'saved-mcp-release-1' } });
        expect(JSON.stringify(savedReplay)).toContain('"replayed":true');
        expect(adapter).toHaveBeenCalledTimes(1);
        adapter.mockClear();
        const invalid = await request('tools/call', { name: 'publish_post', arguments: { accountIds: ['work'], text: 'No request ID' } });
        expect((invalid.result as { isError: boolean }).isError).toBe(true);
        expect(adapter).not.toHaveBeenCalled();
        const args = { requestId: 'mcp-release-1', accountIds: ['work'], text: 'Hello' };
        const posted = await request('tools/call', { name: 'publish_post', arguments: args });
        expect((posted.result as { isError?: boolean }).isError).toBe(false);
        const replayed = await request('tools/call', { name: 'publish_post', arguments: args });
        expect(JSON.stringify(replayed)).toContain('"replayed":true');
        expect(adapter).toHaveBeenCalledTimes(1);
        const operation = await request('tools/call', { name: 'get_operation', arguments: { requestId: 'mcp-release-1' } });
        expect(JSON.stringify(operation)).toContain('https://x.com/i/status/123');
        const guide = await request('resources/read', { uri: 'dotshare://guide' });
        expect(JSON.stringify(guide)).toContain('SAME requestId');
        const prompts = await request('prompts/list');
        expect(JSON.stringify(prompts)).toContain('release-announcement');
        expect(JSON.stringify(publisher.journal.list())).not.toContain('private-work-token');
    } finally { await client.close(); await server.close(); fs.rmSync(home, { recursive: true, force: true }); }
}, 20000);
